import { z } from "zod";
import type { ImpactResult } from "@/lib/impact-engine/engine";
import {
  add,
  precision,
  recall,
  type Counts,
  type ScenarioResult,
} from "@/lib/impact-engine/evaluate";
import { applyUnifiedDiff } from "@/lib/patches/diff";
import { githubNameSchema, repoPathSchema } from "@/lib/schemas";
import type { AssistResult } from "./assist";

const needles = z.array(z.string().min(1).max(200)).max(10);

/** What a correct patch must (not) leave in a labelled doc. */
export const patchLabelsSchema = z.strictObject({
  datasetVersion: z.string().min(1).max(32),
  description: z.string().min(1).max(2000),
  labels: z
    .array(
      z.strictObject({
        scenario: githubNameSchema,
        docPath: repoPathSchema,
        mustContain: needles,
        mustNotContain: needles,
      }),
    )
    .max(200),
});
export type PatchLabel = z.infer<typeof patchLabelsSchema>["labels"][number];

/**
 * Model-assisted flagging: a flagged doc the model judges "no_update" is demoted.
 * When the model failed or was skipped, the deterministic status stands.
 */
export function assistedImpact(result: AssistResult): ImpactResult {
  const demoted = new Set(
    result.assessments
      .filter((a) => a.verdict === "no_update")
      .map((a) => a.docPath),
  );
  return {
    ...result.deterministic,
    candidates: result.deterministic.candidates.map((c) =>
      demoted.has(c.docPath) ? { ...c, status: "unlikely_affected" } : c,
    ),
  };
}

export type PatchLabelOutcome =
  "label_pass" | "label_fail" | "no_valid_patch" | "not_attempted";

/** Checks the validated proposal for a labelled doc, case-insensitively. */
export function checkPatchLabel(
  label: PatchLabel,
  docContent: string,
  result: AssistResult,
): PatchLabelOutcome {
  const outcome = result.outcomes.find((o) => o.docPath === label.docPath);
  if (!outcome || outcome.patch === "not_attempted") return "not_attempted";
  const proposal = result.proposals.find((p) => p.targetPath === label.docPath);
  if (!proposal) return "no_valid_patch";
  const applied = applyUnifiedDiff(label.docPath, docContent, proposal.patch);
  if (!applied.ok) return "no_valid_patch";
  const text = applied.content.toLowerCase();
  const pass =
    label.mustContain.every((s) => text.includes(s.toLowerCase())) &&
    label.mustNotContain.every((s) => !text.includes(s.toLowerCase()));
  return pass ? "label_pass" : "label_fail";
}

/** Nearest-rank percentile; null for no data. */
export function percentile(
  values: readonly number[],
  p: number,
): number | null {
  if (values.length === 0) return null;
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.max(0, Math.ceil((p / 100) * sorted.length) - 1)]!;
}

export interface LlmEvalRun {
  environment: {
    model: string;
    ollamaVersion: string;
    numCtx: number;
    timeoutMs: number;
    promptVersions: string[];
    assistPolicy: string;
    engineVersion: string;
    datasetVersions: string[];
    patchLabelVersion: string;
    date: string;
  };
  scenarios: {
    id: string;
    deterministic: ScenarioResult;
    assisted: ScenarioResult;
    result: AssistResult;
    patches: { docPath: string; outcome: PatchLabelOutcome }[];
  }[];
}

const pct = (v: number | null) =>
  v === null ? "n/a" : `${(v * 100).toFixed(1)}%`;
const secs = (ms: number | null) =>
  ms === null ? "n/a" : `${(ms / 1000).toFixed(1)} s`;
const zero: Counts = { tp: 0, fp: 0, fn: 0, tn: 0 };

/** Markdown report for one run. Not checked for staleness: model output varies. */
export function renderLlmReport(run: LlmEvalRun): string {
  const env = run.environment;
  const det = run.scenarios.reduce(
    (a, s) => add(a, s.deterministic.counts),
    zero,
  );
  const asst = run.scenarios.reduce((a, s) => add(a, s.assisted.counts), zero);
  const row = (name: string, c: Counts) =>
    `| ${name} | ${c.tp} | ${c.fp} | ${c.fn} | ${c.tn} | ${pct(precision(c))} | ${pct(recall(c))} |`;
  const durations = run.scenarios.flatMap((s) => s.result.callDurationsMs);
  const outcomes = run.scenarios.flatMap((s) => s.result.outcomes);
  const patches = run.scenarios.flatMap((s) => s.patches);
  const count = <T>(xs: readonly T[], pred: (x: T) => boolean) =>
    xs.filter(pred).length;
  const attempted = count(outcomes, (o) =>
    ["valid", "rejected", "no_change"].includes(o.patch),
  );
  const issueCounts = new Map<string, number>();
  for (const o of outcomes) {
    for (const i of [...(o.issues ?? []), ...(o.code ? [o.code] : [])]) {
      issueCounts.set(i, (issueCounts.get(i) ?? 0) + 1);
    }
  }
  const statusOf = (r: ScenarioResult, doc: string) =>
    r.docs.find((d) => d.docPath === doc);

  return [
    "# Model-assisted evaluation (Ollama)",
    "",
    "Generated by `npm run eval:llm`. Do not edit by hand. Model output varies by machine, model build and Ollama version, so this file records one run and is not regenerated in CI.",
    "",
    `- Date: ${env.date}`,
    `- Model: \`${env.model}\` via Ollama ${env.ollamaVersion}; temperature 0, seed 42, num_ctx ${env.numCtx}, timeout ${env.timeoutMs} ms`,
    `- Prompts: ${env.promptVersions.map((v) => `\`${v}\``).join(", ")}; assist policy \`${env.assistPolicy}\`; engine \`${env.engineVersion}\``,
    `- Datasets: ${env.datasetVersions.map((v) => `\`${v}\``).join(", ")} (${run.scenarios.length} scenarios); patch labels \`${env.patchLabelVersion}\``,
    "- Assisted mode: the model sees only docs the deterministic engine flagged and may demote them (`no_update`). It cannot add docs, so it cannot raise recall.",
    "",
    "## Flagging: deterministic vs model-assisted",
    "",
    "| Mode | TP | FP | FN | TN | Precision | Recall |",
    "|---|---|---|---|---|---|---|",
    row("Deterministic", det),
    row("Model-assisted", asst),
    "",
    "## Patches",
    "",
    `- Patch requests: ${attempted}; validated proposals: ${count(outcomes, (o) => o.patch === "valid")}; rejected by validation: ${count(outcomes, (o) => o.patch === "rejected")}; model proposed no change: ${count(outcomes, (o) => o.patch === "no_change")}; failed calls: ${count(outcomes, (o) => o.patch === "failed")}`,
    `- Labelled docs (${patches.length}): label pass ${count(patches, (p) => p.outcome === "label_pass")}, label fail ${count(patches, (p) => p.outcome === "label_fail")}, no valid patch ${count(patches, (p) => p.outcome === "no_valid_patch")}, not attempted ${count(patches, (p) => p.outcome === "not_attempted")}`,
    `- Rejection and failure codes: ${
      issueCounts.size === 0
        ? "none"
        : [...issueCounts]
            .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
            .map(([k, v]) => `\`${k}\` ${v}`)
            .join(", ")
    }`,
    `- Model calls: ${durations.length}; latency median ${secs(percentile(durations, 50))}, p95 ${secs(percentile(durations, 95))}`,
    "",
    "## Per flagged doc",
    "",
    "| Scenario | Doc | Labelled | Deterministic | Model verdict | Assisted outcome | Patch | Label check |",
    "|---|---|---|---|---|---|---|---|",
    ...run.scenarios.flatMap((s) =>
      s.result.outcomes.map((o) => {
        const d = statusOf(s.deterministic, o.docPath);
        const a = statusOf(s.assisted, o.docPath);
        const label = s.patches.find((p) => p.docPath === o.docPath);
        const patch = o.issues
          ? `${o.patch} (${o.issues.join(", ")})`
          : o.code
            ? `${o.patch} (${o.code})`
            : o.patch;
        return `| ${s.id} | ${o.docPath} | ${d?.labelled ? "yes" : "no"} | ${d?.status ?? "n/a"} | ${o.assessment} | ${a?.outcome.toUpperCase() ?? "n/a"} | ${patch} | ${label?.outcome ?? "unlabelled"} |`;
      }),
    ),
    "",
    "## Limits",
    "",
    "- One run on 21 small synthetic scenarios, with a few flagged docs each. The differences are anecdotal and are not an estimate of real-world performance.",
    "- Labels (impact and patch) and prompts have the same author. Patch labels were written before any model output was read. The prompts were not changed after reading results, but the assist policy was, on these same fixtures (docs/08), so these numbers are not a held-out result.",
    "- `label_pass` checks a few required and forbidden strings, not the quality of the prose. Every proposal still needs human review.",
    "",
  ].join("\n");
}
