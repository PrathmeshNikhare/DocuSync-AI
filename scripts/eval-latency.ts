// Usage: npm run eval:latency
// Times the deterministic engine on every fixture scenario and counts failures,
// then writes docs/evaluation/impact-latency.md. Timings depend on the machine,
// so the report records the date, the machine and the run size, and is not
// checked by the test suite (impact-baseline.md, which is deterministic, is).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { performance } from "node:perf_hooks";
import { runScenario, scenarioSchema } from "@/lib/impact-engine/evaluate";
import { ENGINE_VERSION } from "@/lib/impact-engine/config";

const RUNS = 20;
const dir = path.join(process.cwd(), "fixtures", "impact");
const scenarios = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((f) =>
    scenarioSchema.parse(JSON.parse(readFileSync(path.join(dir, f), "utf8"))),
  );

const times: number[] = [];
let failures = 0;
for (const s of scenarios) runScenario(s); // warm-up, not measured
for (let i = 0; i < RUNS; i++) {
  for (const s of scenarios) {
    const t0 = performance.now();
    try {
      runScenario(s);
    } catch {
      failures++;
    }
    times.push(performance.now() - t0);
  }
}
times.sort((a, b) => a - b);
const q = (p: number) =>
  times[Math.min(times.length - 1, Math.floor(p * times.length))]!;
const ms = (v: number) => `${v.toFixed(2)} ms`;

const report = [
  "# Impact engine latency and failures (deterministic)",
  "",
  "Generated by `npm run eval:latency`. Timings depend on the machine; re-run to reproduce on yours.",
  "",
  `- Date: ${new Date().toISOString().slice(0, 10)}`,
  `- Machine: ${os.cpus()[0]?.model.trim() ?? "unknown CPU"}, ${os.cpus().length} logical CPUs, ${os.platform()} ${os.release()}, Node ${process.version}`,
  `- Engine: \`${ENGINE_VERSION}\`; ${scenarios.length} scenarios × ${RUNS} runs = ${times.length} timed analyses (one warm-up pass not timed)`,
  "- Scope: `analyzeImpact` on in-memory fixtures. Excludes GitHub fetches, the database and the model (see `llm-assisted.md` for model latency).",
  "",
  "| Measure | Value |",
  "|---|---|",
  `| Median | ${ms(q(0.5))} |`,
  `| p95 | ${ms(q(0.95))} |`,
  `| Max | ${ms(times[times.length - 1]!)} |`,
  `| Failures (exceptions) | ${failures} of ${times.length} |`,
  "",
].join("\n");
writeFileSync(
  path.join(process.cwd(), "docs", "evaluation", "impact-latency.md"),
  report,
);
console.log(
  `${times.length} analyses: median ${ms(q(0.5))}, p95 ${ms(q(0.95))}, failures ${failures}`,
);
